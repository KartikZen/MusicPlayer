// Render Playlist
function renderPlaylist() {
    playlistList.innerHTML = '';

    // Use filtered playlist if search is active, otherwise use current playlist
    const displayPlaylist = filteredPlaylist.length > 0 ? filteredPlaylist : currentPlaylist;

    displayPlaylist.forEach((song, idx) => {
        const isFavorite = favorites.some(fav =>
            fav.name === song.name && fav.artist === song.artist
        );

        const li = document.createElement('li');
        li.innerHTML = `
                    <img src="${song.img}" alt="${song.name}" class="song-img-small">
                    <div class="song-info">
                        <div class="song-title">${song.name}</div>
                        <div class="song-artist">${song.artist}</div>
                    </div>
                    <i class="bi ${isFavorite ? 'bi-heart-fill favorite-btn favorite' : 'bi-heart favorite-btn'}" data-id="${idx}"></i>
                `;

        li.addEventListener('click', (e) => {
            if (!e.target.classList.contains('favorite-btn')) {
                // Find the actual index in the current playlist
                const actualIndex = currentPlaylist.findIndex(s =>
                    s.name === song.name && s.artist === song.artist
                );

                if (actualIndex !== -1) {
                    loadSong(actualIndex);
                    audio.play();
                    playBtn.classList.remove('bi-play-fill');
                    playBtn.classList.add('bi-pause-fill');
                    songImg.classList.add('playing');
                    playlistModal.style.display = 'none';
                }
            }
        });

        // Add favorite toggle
        const heartIcon = li.querySelector('.favorite-btn');
        heartIcon.addEventListener('click', (e) => {
            e.stopPropagation();
            toggleFavorite(song);
            renderPlaylist();
        });

        playlistList.appendChild(li);
    });

    highlightCurrentSong();
    updatePlaylistStats();
}

// Render Custom Playlists
function renderCustomPlaylists() {
    customPlaylistList.innerHTML = '';

    Object.keys(customPlaylists).forEach(playlistName => {
        const playlist = customPlaylists[playlistName];
        const li = document.createElement('li');
        li.innerHTML = `
                    <div>
                        <div class="playlist-name">${playlistName}</div>
                        <div class="playlist-song-count">${playlist.length} songs</div>
                    </div>
                    <div class="playlist-actions">
                        <button class="playlist-action-btn play-playlist" title="Play Playlist">
                            <i class="bi bi-play-fill"></i>
                        </button>
                        <button class="playlist-action-btn add-to-playlist" title="Add Current Song">
                            <i class="bi bi-plus-circle"></i>
                        </button>
                        <button class="playlist-action-btn delete-playlist" title="Delete Playlist">
                            <i class="bi bi-trash"></i>
                        </button>
                    </div>
                `;

        // Play playlist
        li.querySelector('.play-playlist').addEventListener('click', (e) => {
            e.stopPropagation();
            if (playlist.length > 0) {
                currentPlaylist = playlist;
                currentSong = 0;
                loadSong(0);
                audio.play();
                playBtn.classList.remove('bi-play-fill');
                playBtn.classList.add('bi-pause-fill');
                songImg.classList.add('playing');
                customPlaylistModal.style.display = 'none';
                playlistModal.style.display = 'none';
            } else {
                showToast('This playlist is empty!');
            }
        });

        // Add current song to playlist
        li.querySelector('.add-to-playlist').addEventListener('click', (e) => {
            e.stopPropagation();
            const currentSongData = currentPlaylist[currentSong];
            if (!playlist.some(song =>
                song.name === currentSongData.name && song.artist === currentSongData.artist)) {
                playlist.push(currentSongData);
                customPlaylists[playlistName] = playlist;
                localStorage.setItem('customPlaylists', JSON.stringify(customPlaylists));
                renderCustomPlaylists();
                showToast(`"${currentSongData.name}" added to "${playlistName}"`);
            } else {
                showToast(`"${currentSongData.name}" is already in "${playlistName}"`);
            }
        });

        // Delete playlist
        li.querySelector('.delete-playlist').addEventListener('click', (e) => {
            e.stopPropagation();
            if (confirm(`Are you sure you want to delete "${playlistName}"?`)) {
                delete customPlaylists[playlistName];
                localStorage.setItem('customPlaylists', JSON.stringify(customPlaylists));
                renderCustomPlaylists();
            }
        });

        customPlaylistList.appendChild(li);
    });
}

// Create new playlist
createPlaylistBtn.addEventListener('click', () => {
    const name = newPlaylistName.value.trim();
    if (name) {
        if (!customPlaylists[name]) {
            customPlaylists[name] = [];
            localStorage.setItem('customPlaylists', JSON.stringify(customPlaylists));
            newPlaylistName.value = '';
            renderCustomPlaylists();
        } else {
            showToast('A playlist with this name already exists!');
        }
    } else {
        showToast('Please enter a playlist name!');
    }
});

// Update playlist stats
function updatePlaylistStats() {
    const totalSongs = currentPlaylist.length;
    const favoriteSongs = currentPlaylist.filter(song =>
        favorites.some(fav => fav.name === song.name && fav.artist === song.artist)
    ).length;

    if (filteredPlaylist.length > 0) {
        playlistStats.textContent = `${filteredPlaylist.length} of ${totalSongs} songs (${favoriteSongs} favorites)`;
    } else {
        playlistStats.textContent = `${totalSongs} songs (${favoriteSongs} favorites)`;
    }
}

// Playlist search functionality
playlistSearchInput.addEventListener('input', (e) => {
    const query = e.target.value.toLowerCase().trim();

    if (query === '') {
        filteredPlaylist = [];
    } else {
        filteredPlaylist = currentPlaylist.filter(song =>
            song.name.toLowerCase().includes(query) ||
            song.artist.toLowerCase().includes(query)
        );
    }

    renderPlaylist();
});

