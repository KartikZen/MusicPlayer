// Next Song
function nextSong() {
    if (isShuffled) {
        loadSong(Math.floor(Math.random() * currentPlaylist.length));
    } else {
        loadSong((currentSong + 1) % currentPlaylist.length);
    }
    audio.play();
    playBtn.classList.remove('bi-play-fill');
    playBtn.classList.add('bi-pause-fill');
    songImg.classList.add('playing');
}

// Previous Song
function prevSong() {
    if (audio.currentTime > 3) {
        audio.currentTime = 0;
    } else {
        if (isShuffled) {
            loadSong(Math.floor(Math.random() * currentPlaylist.length));
        } else {
            loadSong((currentSong - 1 + currentPlaylist.length) % currentPlaylist.length);
        }
        audio.play();
        playBtn.classList.remove('bi-play-fill');
        playBtn.classList.add('bi-pause-fill');
        songImg.classList.add('playing');
    }
}

