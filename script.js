// Update lyrics based on current time
function updateLyrics() {
    if (!currentLyrics || currentLyrics.length === 0) return;

    const currentTime = audio.currentTime;
    let newIndex = -1;

    // Find the current lyric based on time
    for (let i = 0; i < currentLyrics.length; i++) {
        if (currentTime >= currentLyrics[i].time) {
            newIndex = i;
        } else {
            break;
        }
    }

    // Update active lyric if changed
    if (newIndex !== currentLyricIndex) {
        currentLyricIndex = newIndex;
        renderLyrics();
    }
}

// Render lyrics in the lyrics modal
function renderLyrics() {
    if (!lyricsContainer) return;

    lyricsContainer.innerHTML = '';

    if (!currentLyrics || currentLyrics.length === 0) {
        lyricsContainer.innerHTML = '<div class="no-lyrics">No lyrics available for this song</div>';
        return;
    }

    currentLyrics.forEach((line, index) => {
        const lineEl = document.createElement('div');
        lineEl.className = 'lyrics-line';
        lineEl.textContent = line.text;

        if (index === currentLyricIndex) {
            lineEl.classList.add('active');
        }

        lyricsContainer.appendChild(lineEl);
    });

    // Scroll to active lyric
    const activeLine = lyricsContainer.querySelector('.lyrics-line.active');
    if (activeLine) {
        activeLine.scrollIntoView({ behavior: 'smooth', block: 'center' });
    }
}

