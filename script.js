// Keyboard shortcuts
document.addEventListener('keydown', (e) => {
    if (e.code === 'Space') {
        e.preventDefault();
        togglePlay();
    } else if (e.code === 'ArrowRight') {
        nextSong();
    } else if (e.code === 'ArrowLeft') {
        prevSong();
    } else if (e.code === 'ArrowUp') {
        audio.volume = Math.min(1, audio.volume + 0.1);
        volumeBar.value = audio.volume; volumeBar.style.setProperty('--vol', `${audio.volume * 100}%`);
    } else if (e.code === 'ArrowDown') {
        audio.volume = Math.max(0, audio.volume - 0.1);
        volumeBar.value = audio.volume; volumeBar.style.setProperty('--vol', `${audio.volume * 100}%`);
    } else if (e.code === 'Escape') {
        // Close modals with Escape key
        if (playlistModal.style.display === 'flex') {
            playlistModal.style.display = 'none';
        }
        if (customPlaylistModal.style.display === 'flex') {
            customPlaylistModal.style.display = 'none';
        }
        if (lyricsModal.style.display === 'flex') {
            lyricsModal.style.display = 'none';
        }
        if (timerModal.style.display === 'flex') {
            timerModal.style.display = 'none';
        }
    }
});

// Favorites functionality
function toggleFavorite(song) {
    const index = favorites.findIndex(fav =>
        fav.name === song.name && fav.artist === song.artist
    );

    if (index === -1) {
        favorites.push(song);
    } else {
        favorites.splice(index, 1);
    }

    localStorage.setItem('favorites', JSON.stringify(favorites));
    updateFavoritesButton();
    updatePlaylistStats();
}

